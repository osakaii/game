/**
 * Без ответа на пинг дольше этого — связь мёртвая. Пинг уходит раз в 2 с: это три пропуска подряд.
 * Один пропуск — ещё не обрыв (пакет застрял в очереди на медленном 3G).
 */
export const DEAD_LINK_MS = 6000;

/**
 * Сторож связи. Когда телефон уходит из Wi-Fi в мобильную сеть, старое TCP-соединение не рвётся,
 * а просто молчит: socket.io замечает это только по своему пингу — через десятки секунд.
 * У нас свой пинг каждые 2 с, и по нему видно сразу: ответы перестали приходить — пора переподключаться.
 */
export class LinkWatchdog {
  private lastAlive = 0;

  /** Пришёл ответ сервера (или связь только что установлена). */
  alive(now: number): void {
    this.lastAlive = now;
  }

  isDead(now: number): boolean {
    return now - this.lastAlive > DEAD_LINK_MS;
  }
}
